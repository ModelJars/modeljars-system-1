#!/usr/bin/env bash
# Regenerates ../../article/tictactoe-results.md from the raw records and timing logs. Nothing in that file is typed by hand.
set -euo pipefail
cd "$(dirname "$0")"
RUNS=../../article/runs/tictactoe
OUT=../../article/tictactoe-results.md
{
cat <<'HEAD'
# Tic-tac-toe as a typed decision: measured results (2026-10-29)

Generated by `code/tictactoe/make-results.sh` (the table by `summarize.py`) from the per-decision
records and timing logs in `article/runs/tictactoe/` (`laptop/`, `vps/`, `jev/`; machine descriptions
and notes beside each). The model always plays O. Each bench decision asked three questions about one
board: which empty cell to play (a Choice over the legal cells), "can O win right now" and "if O does
not block, can X win next" (two Nouls). Ground truth is minimax, stored in every record. "Top cell
optimal" counts the model's most probable cell among the minimax-optimal moves; "took a win" and
"blocked" count the positions where a win or a block was available. Positions: 69 sampled from random
play with a fixed seed, then whole games against a random X (10) and a perfect X (3). Board texts:
`GRID` (ASCII board plus the empty cells), `LIST` (cells held by X, O and nobody), `_HINTS` variants
prepend the rules and a one-line strategy. Jev was called from the laptop over its API; its times are
the HTTP round trip. Every Harriet probability was identical on the laptop and the VPS (checked on
all 114 GRID decisions).

HEAD
python3 summarize.py "$RUNS"
cat <<'MID'

## What one move costs (fresh boards)

`TicTacToeTiming.java`: every measurement on a board the runtime had not seen; the last column is a
second question on a board it had just answered, which reuses the prefix. The laptop is the 2019
MacBook Pro (`runs/ENVIRONMENT.txt`), uncontended; the VPS is a Hetzner CCX33, 4 dedicated EPYC Milan
cores, first of two consecutive runs.

Laptop (`laptop/timing.log`):

MID
echo '```'; grep "backend\|state" "$RUNS/laptop/timing.log"; echo '```'
echo; echo 'CCX33 (`vps/timing-ccx33.log`):'; echo
echo '```'; grep "backend\|state" "$RUNS/vps/timing-ccx33.log"; echo '```'
if [ -f "$RUNS/vps/timing-ccx43.log" ]; then echo; echo 'CCX43, 16 vCPU (`vps/timing-ccx43.log`):'; echo; echo '```'; grep "backend\|state" "$RUNS/vps/timing-ccx43.log"; echo '```'; fi
cat <<'TAIL'

The bench's laptop median above (11.9 s per three-question decision) was contended by a demo game and
the hosted-arm bench on the same machine; the uncontended laptop cost is the probe's 9.8 s. The VPS
bench median (3.6 s) is below the probe's 5.3 s because bench positions have fewer empty cells on
average than the probe's six-empty boards, so shorter option lists.
TAIL
} > "$OUT"
echo "wrote $OUT"
